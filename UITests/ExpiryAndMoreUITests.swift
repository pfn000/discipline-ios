import XCTest

final class ExpiryUITests: DisciplineUITestCase {
    func testTrackRefreshRemindAndBudget() {
        launch()
        tab("Expiry")
        XCTAssertTrue(el("expiry.empty").waitForExistence(timeout: 5))
        snap("11-expiry-empty")
        tap("expiry.add")
        tap("add.cancel")
        tap("expiry.add")
        XCTAssertFalse(el("add.save").isEnabled, "Add needs a name")
        type("add.name", "LiveContainer")
        type("add.bundleID", "com.kdt.livecontainer")
        XCTAssertTrue(el("add.date").exists)
        snap("12-expiry-add")
        tap("add.save")
        expectToast(contains: "Tracking LiveContainer")
        dismissToast()
        let left = el("expiry.left.com.kdt.livecontainer")
        XCTAssertTrue(left.waitForExistence(timeout: 5))
        XCTAssertTrue(left.label.hasPrefix("6d"), "fresh 7-day signature shows 6d…, got \(left.label)")
        tap("expiry.refreshed.com.kdt.livecontainer")
        expectToast(contains: "LiveContainer marked refreshed")
        dismissToast()
        flip("expiry.reminders")
        expectToast(contains: "Reminders on: 3 scheduled")
        dismissToast()
        tap("expiry.logAppID")
        expectToast(contains: "Logged 1 App ID")
        dismissToast()
        XCTAssertTrue(el("expiry.budgetGauge").exists)
        snap("13-expiry-tracked")
        tap("expiry.resetBudget")
        expectToast(contains: "App ID log cleared")
        dismissToast()
        flip("expiry.reminders")
        expectToast(contains: "Reminders off")
        dismissToast()
        // Home now counts down and can mark everything refreshed.
        tab("Home")
        XCTAssertTrue(el("home.countdown").waitForExistence(timeout: 5))
        snap("14-home-countdown")
        tap("home.markAllRefreshed")
        expectToast(contains: "All apps marked refreshed")
        dismissToast()
        tab("Expiry")
        let row = el("expiry.row.com.kdt.livecontainer")
        row.swipeLeft()
        app.buttons["Stop tracking"].firstMatch.tap()
        XCTAssertTrue(el("expiry.empty").waitForExistence(timeout: 5))
    }
}

final class MoreUITests: DisciplineUITestCase {
    func testSettingsEveryControl() {
        launch()
        openMore("more.settings")
        snap("15-settings")
        tap("settings.tier")
        app.buttons["Paid developer (1 year)"].firstMatch.tap()
        app.segmentedControls["settings.appearance"].buttons["Dark"].tap()
        snap("16-settings-dark")
        app.segmentedControls["settings.appearance"].buttons["System"].tap()
        tap("settings.tint")
        app.buttons["Rose"].firstMatch.tap()
        type("settings.tunnelIP", "10.7.1.1")
        flip("settings.prereleases")
        type("settings.token", "ghp_test_token")
        tap("settings.saveToken")
        expectToast(contains: "Token saved in the Keychain")
        dismissToast()
        tap("settings.removeToken")
        expectToast(contains: "Token removed")
        dismissToast()
        tap("settings.makeBackup")
        tap("settings.shareBackup")
        expectShareSheetAndClose()
        tap("settings.restore")
        expectDocumentPickerAndCancel()
        // The paid tier changes the App ID section.
        tab("Expiry")
