        tab("More")
        back()
        tap("more.support")
        snap("18-support")
        tap("support.tip")
        expectOtherApp("com.apple.mobilesafari", showing: "stripe.com")
        back()
        tap("more.limits")
        snap("19-limits")
        back()
        tap("more.about")
        snap("20-about")
    }

